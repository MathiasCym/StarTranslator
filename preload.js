const { contextBridge, ipcRenderer, webUtils } = require('electron')

contextBridge.exposeInMainWorld('api', {
  appVersion: () => ipcRenderer.invoke('app-version'),
  updateState: () => ipcRenderer.invoke('update-state'),
  startupUpdateNotice: () => ipcRenderer.invoke('startup-update-notice'),
  ignoreUpdateNotice: version => ipcRenderer.invoke('ignore-update-notice',version),
  checkUpdates: () => ipcRenderer.invoke('check-updates'),
  downloadUpdate: () => ipcRenderer.invoke('download-update'),
  cancelUpdate: () => ipcRenderer.invoke('cancel-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  onUpdateStatus: cb => ipcRenderer.on('update-status', (_event,value) => cb(value)),
  openMaintenanceAuthorization: () => ipcRenderer.invoke('open-maintenance-authorization'),
  exportDiagnostics: (task) => ipcRenderer.invoke('export-diagnostics', task),
  changelog: () => ipcRenderer.invoke('app-changelog'),
  copyAuthorEmail: () => ipcRenderer.invoke('copy-author-email'),
  checkInstallation: (allowServiceRestart = false) => ipcRenderer.invoke('check-installation', allowServiceRestart),
  onInstallationStatus: (cb) => ipcRenderer.on('installation-status', (_e, status) => cb(status)),
  modelStatus: () => ipcRenderer.invoke('model-status'),
  onModelStatus: (cb) => ipcRenderer.on('model-status', (_e, status) => cb(status)),
  backendPort: () => ipcRenderer.invoke('backend-port'),
  api: (method, path, body) => ipcRenderer.invoke('api', { method, path, body }),
  openSharedService: address => ipcRenderer.invoke('open-shared-service', address),
  pickFiles: () => ipcRenderer.invoke('pick-files'),
  pickReferences: () => ipcRenderer.invoke('pick-references'),
  pickSharedLexicon: (create = false) => ipcRenderer.invoke('pick-shared-lexicon', create),
  pickGlossary: () => ipcRenderer.invoke('pick-glossary'),
  exportGlossaryPath: (format) => ipcRenderer.invoke('export-glossary-path',format),
  pathForFile: (file) => webUtils.getPathForFile(file),
  openFolder: (p) => ipcRenderer.invoke('open-folder', p),
  openFile: (p) => ipcRenderer.invoke('open-file', p),
  minimize: () => ipcRenderer.invoke('window-minimize'),
  toggleMaximize: () => ipcRenderer.invoke('window-maximize'),
  closeWindow: () => ipcRenderer.invoke('window-close'),
  closeGuardReady: () => ipcRenderer.invoke('window-close-ready'),
  answerCloseRequest: (token, accepted) => ipcRenderer.invoke('window-close-answer', token, accepted),
  onCloseRequest: cb => ipcRenderer.on('window-close-request', (_event, token) => cb(token)),
  onMaximizeChange: (cb) => ipcRenderer.on('window-maximized', (_e, v) => cb(v)),
  pickDirectory: (defaultPath) => ipcRenderer.invoke('pick-directory', defaultPath),
  getGlossarySources: () => ipcRenderer.invoke('get-glossary-sources'),
  setGlossarySources: (sources) => ipcRenderer.invoke('set-glossary-sources', sources),
  onBackendReady: (cb) => ipcRenderer.on('backend-ready', (_e, port) => cb(port)),
  onBackendError: (cb) => ipcRenderer.on('backend-error', (_e, msg) => cb(msg)),
})
